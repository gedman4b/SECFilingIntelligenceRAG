"""
eval/benchmark.py

Hand-verified question/answer pairs: the regression suite for the query
pipeline.

Design principle
-----------------
Part 7 of the write-up defines "correct" on three axes: value correctness
(with scale normalization), period correctness, and provenance
correctness (the citation points to a page and table where the value
actually appears). This module encodes exactly those three axes per case,
plus, for growth/comparison cases, an independently computed expected
result -- independently meaning worked out by hand with plain arithmetic,
not by calling agents/numerical_reasoner.py. A benchmark whose expected
values were generated by the function under test could never catch a bug
in that function.

Every numeric value below was hand-verified against the actual filing
PDFs in ingest/pdfs/ during development: parsed with pdf_parser.py,
rendered with table_classifier.render_table_as_text(), and read directly
off the resulting table text, the same "open the PDF, locate the exact
table, copy the value" process Part 7 describes for a human analyst. Each
ExpectedFact carries the exact page number where the value appears.

Narrative correctness is not exact-match (Part 7: "Exact match is not
meaningful here"). Narrative cases carry expected_passage_keywords as a
coarse automated sanity check only; the real correctness signal is human
relevance rating on a 1-3 scale, which this file has no field for because
it cannot be filled in automatically -- see eval/runner.py.

Composition matches the write-up's Part 7 benchmark: 10 numeric_lookup,
6 growth_calc, 2 comparison, 2 narrative, across Tesla and Apple's actual
10-K filings in ingest/pdfs/.

Dependencies
------------
pydantic >= 2.0

Author: Scott Josephson  |  Deloitte SEC Filing Intelligence take-home
"""

