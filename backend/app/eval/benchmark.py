# =============================================================================
# Case schema
# =============================================================================

class ExpectedFact(BaseModel):
    """Ground truth for one raw fact a case expects the Fact Retriever to
    return, hand-verified against the source PDF."""
    metric_canonical_id: str
    year: int
    quarter: Optional[int] = None
    expected_value: float
    expected_units: str
    expected_page: int
    filing_id: str


class BenchmarkCase(BaseModel):
    """One hand-verified question/answer pair.

    `plan` is the golden QueryPlan a correct Query Planner interpretation
    of `question` should produce. eval/runner.py's default (offline) run
    uses this plan directly and never calls the Planner's LLM, per
    AGENTS.md: "No test that requires network access to a live LLM
    provider runs in the default suite."
    """
    case_id: str
    question: str
    question_type: QuestionType
    company_ticker: str
    plan: QueryPlan
    expected_facts: List[ExpectedFact] = Field(default_factory=list)
    expected_computed_value: Optional[float] = None
    expected_computed_tolerance: float = 0.01
    expected_confidence: str = "high"
    expected_passage_keywords: List[str] = Field(default_factory=list)
    notes: str = ""


